# frozen_string_literal: true

# Writes lib/asciiunits/model/nodes.rb, the LutaML Model classes of the
# AsciiUnits parse tree, from the static capture shapes of the compiled
# artifact (scripts/capture_shapes.rb over artifacts/unitsml.json).
#
# Usage:
#   ruby scripts/generate_model.rb            write the classes
#   ruby scripts/generate_model.rb --check    exit 1 if they are stale
#
# The mapping is mechanical:
#
#   capture of kind text  -> the shared class Slice, the parsanol slice
#                            as the tree serializes it (value, offset,
#                            length, line, column)
#   capture of kind hash  -> class <Capture>, one attribute per key
#   capture in EXPRESSION -> the shared class Expression, declaring the
#                            union of their keys and the root's keys
#
# EXPRESSION holds the recursive captures (int_exp, sequence, sqrt nest in
# each other and in themselves) and the tree itself, which has the same
# keys. One class for them keeps the class graph free of cycles of two or
# more classes, as in the umath and amath generators. Generation fails on a
# capture that holds more than one kind, nil only, or a list, and on any
# class cycle left outside Expression.

require_relative "capture_shapes"

ROOT = File.expand_path("..", __dir__)
ARTIFACT = File.join(ROOT, "artifacts/unitsml.json")
OUT = File.join(ROOT, "lib/asciiunits/model/nodes.rb")
NS = "Asciiunits::Model"
SLICE_CLASS = "Slice"
EXPRESSION_CLASS = "Expression"
EXPRESSION = %w[int_exp sequence sqrt].freeze

check = ARGV.delete("--check")
abort "usage: ruby scripts/generate_model.rb [--check]" unless ARGV.empty?

shapes = CaptureShapes.new(ARTIFACT)
caps = shapes.captures

kind = lambda do |name|
  held = caps.fetch(name).kinds - [:nil]
  unless held.size == 1 && %i[text hash].include?(held.first)
    abort "capture #{name} holds #{caps[name].kinds.to_a.join('|').then { |k| k.empty? ? 'nothing' : k }}; " \
          "the generator maps text and hash captures only"
  end
  held.first
end
unknown = EXPRESSION - caps.keys
abort "EXPRESSION names captures the artifact does not have: #{unknown.join(', ')}" unless unknown.empty?
abort "the tree root is not a hash" unless shapes.root.kinds == Set[:hash]

camel = ->(n) { n.split("_").map { |w| w[0].upcase + w[1..] }.join }
class_of = ->(name) { EXPRESSION.include?(name) ? EXPRESSION_CLASS : camel.call(name) }

classes = { EXPRESSION_CLASS => [["the tree"], shapes.root.keys.to_a.sort] }
caps.each_key do |name|
  next unless kind.call(name) == :hash

  cname = class_of.call(name)
  held, keys = classes[cname] || [[], []]
  abort "class name #{cname} is used by #{held.join(', ')} and #{name}" unless held.empty? || cname == EXPRESSION_CLASS
  classes[cname] = [held + [name], (keys | caps[name].keys.to_a).sort]
end
abort "class name #{SLICE_CLASS} clashes with a capture" if classes.key?(SLICE_CLASS)

require "tsort"
edges = classes.to_h do |cname, (_, keys)|
  [cname, keys.filter_map { |k| class_of.call(k) if kind.call(k) == :hash }.uniq - [cname]]
end
graph = edges.reject { |c, _| c == EXPRESSION_CLASS }.transform_values { |v| v - [EXPRESSION_CLASS] }
cycles = TSort.strongly_connected_components(->(&b) { graph.each_key(&b) }, ->(n, &b) { graph.fetch(n).each(&b) })
              .select { |c| c.size > 1 }
abort "class cycles outside #{EXPRESSION_CLASS}: #{cycles.map { |c| c.sort.join(' ') }.join('; ')}" unless cycles.empty?

type_of = ->(key) { %("#{NS}::#{kind.call(key) == :text ? SLICE_CLASS : class_of.call(key)}") }

out = +<<~RUBY
  # frozen_string_literal: true

  # GENERATED by scripts/generate_model.rb from the static capture shapes
  # of artifacts/unitsml.json -- do not edit. #{classes.size + 1} classes; Document
  # is in lib/asciiunits/model.rb.
  module Asciiunits
    module Model
      # The text of a capture: a parsanol slice as the tree serializes it.
      # +offset+ and +length+ count characters; +line+ and +column+ are
      # 1-based.
      class #{SLICE_CLASS} < Lutaml::Model::Serializable
        attribute :value, :string
        attribute :offset, :integer
        attribute :length, :integer
        attribute :line, :integer
        attribute :column, :integer
      end

RUBY
classes.sort.each do |cname, (held, keys)|
  what = if held.size > 1 then "The tree and the captures #{held.drop(1).map { |c| "+#{c}+" }.join(', ')}"
         else "Capture +#{held.first}+"
         end
  comment = "# #{what}.".gsub(/(.{1,72})(\s+|\z)/, "\\1\n").lines.map { |l| "    #{l.start_with?('#') ? l : "# #{l}"}" }.join
  out << "#{comment}    class #{cname} < Lutaml::Model::Serializable\n"
  keys.each { |k| out << "      attribute :#{k}, #{type_of.call(k)}\n" }
  out << "    end\n\n"
end
out.chomp!("\n")
out << "  end\nend\n"

rel = OUT.delete_prefix("#{ROOT}/")
if check
  if File.exist?(OUT) && File.binread(OUT) == out.b
    puts "#{rel} is up to date"
  else
    warn "#{rel} is stale; run ruby scripts/generate_model.rb"
    exit 1
  end
else
  File.binwrite(OUT, out)
  puts "wrote #{rel}: #{classes.size + 1} classes"
end
